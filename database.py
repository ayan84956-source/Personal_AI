import sqlite3
import os
from contextlib import contextmanager
from pathlib import Path
from urllib.parse import urlsplit

DB_PATH = Path(__file__).parent / "data" / "personal_ai.db"

def _database_url():
    return os.getenv("DATABASE_URL", "").strip()

def _uses_postgres():
    return bool(_database_url())

def _validate_database_url(database_url):
    """Reject common connection-string placeholders before connecting."""
    try:
        parsed_url = urlsplit(database_url)
        hostname = parsed_url.hostname
        parsed_url.port
    except ValueError as error:
        raise ValueError(
            "DATABASE_URL has an invalid host or port. Use the complete "
            "PostgreSQL connection URL from your database provider."
        ) from error

    placeholders = {"host", "hostname", "db_host", "your-host"}
    if not hostname or hostname.lower() in placeholders:
        raise ValueError(
            "DATABASE_URL is using a placeholder hostname. Replace it with "
            "the real database host from your PostgreSQL provider."
        )


@contextmanager
def get_connection():
    DATABASE_URL = _database_url()
    if DATABASE_URL:
        if not DATABASE_URL.startswith(("postgres://", "postgresql://")):
            raise ValueError(
                "DATABASE_URL must be a PostgreSQL connection URL."
            )
        _validate_database_url(DATABASE_URL)

        import psycopg
        from psycopg.rows import dict_row

        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    else:
        DB_PATH.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(DB_PATH)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")

    try:
        with conn:
            yield conn
    finally:
        conn.close()


def _execute(conn, query, params=()):
    if _uses_postgres():
        query = query.replace("?", "%s")
    return conn.execute(query, params)


def initialize_database():
    if _uses_postgres():
        id_type = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        reference_type = "BIGINT"
    else:
        id_type = "INTEGER PRIMARY KEY AUTOINCREMENT"
        reference_type = "INTEGER"

    with get_connection() as conn:
        conn.execute(f"""
            CREATE TABLE IF NOT EXISTS conversations (
                id {id_type},
                title TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute(f"""
            CREATE TABLE IF NOT EXISTS messages (
                id {id_type},
                conversation_id {reference_type} NOT NULL,
                role TEXT NOT NULL,
                content TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (conversation_id)
                    REFERENCES conversations(id)
            )
        """)
        conn.execute(f"""
            CREATE TABLE IF NOT EXISTS memories (
                id {id_type},
                fact TEXT NOT NULL UNIQUE,
                category TEXT NOT NULL DEFAULT 'general',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS app_preferences (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL
            )
        """)

def create_conversation(title="New conversation"):
    with get_connection() as conn:
        if _uses_postgres():
            return _execute(
                conn,
                "INSERT INTO conversations (title) VALUES (?) RETURNING id",
                (title,),
            ).fetchone()["id"]

        cursor = _execute(
            conn,
            "INSERT INTO conversations (title) VALUES (?)",
            (title,)
        )
        return cursor.lastrowid

def save_message(conversation_id, role, content):
    with get_connection() as conn:
        _execute(
            conn,
            """
            INSERT INTO messages (conversation_id, role, content)
            VALUES (?, ?, ?)
            """,
            (conversation_id, role, content)
        )

def get_conversations():
    with get_connection() as conn:
        return _execute(
            conn,
            "SELECT * FROM conversations ORDER BY id DESC"
        ).fetchall()


def update_conversation_title(conversation_id, title):
    with get_connection() as conn:
        _execute(
            conn,
            "UPDATE conversations SET title = ? WHERE id = ?",
            (title, conversation_id),
        )


def get_messages(conversation_id):
    with get_connection() as conn:
        return _execute(
            conn,
            """
            SELECT role, content FROM messages
            WHERE conversation_id = ?
            ORDER BY id ASC
            """,
            (conversation_id,)
        ).fetchall()

def save_memory(fact, category="general"):
    """Save a useful fact, avoiding duplicates."""
    fact = fact.strip()

    if not fact:
        return

    with get_connection() as conn:
        _execute(
            conn,
            """
            INSERT INTO memories (fact, category)
            VALUES (?, ?)
            ON CONFLICT(fact) DO UPDATE SET
                category = excluded.category
            """,
            (fact, category),
        )

def get_all_memories():
    """Return all saved memories."""
    with get_connection() as conn:
        return _execute(
            conn,
            "SELECT id, fact, category, created_at "
            "FROM memories ORDER BY id DESC"
        ).fetchall()


def delete_memory(memory_id):
    """Delete one memory by its ID."""
    with get_connection() as conn:
        _execute(
            conn,
            "DELETE FROM memories WHERE id = ?",
            (memory_id,),
        )


def search_memories(query, limit=8):
    """Find memories that share keywords with the query."""
    import re

    stop_words = {
        "the", "and", "for", "with", "that", "this", "have",
        "what", "when", "where", "your", "you", "are", "was",
        "how", "can", "does", "from", "about", "tell", "me",
        "please", "help", "into", "want", "like", "use",
    }

    def keywords(text):
        return {
            word for word in re.findall(
                r"[a-zA-Z0-9]+", text.lower()
            )
            if len(word) > 2 and word not in stop_words
        }

    query_words = keywords(query)

    memories = get_all_memories()
    scored = []

    for memory in memories:
        fact_words = keywords(memory["fact"])
        score = len(query_words & fact_words)

        if score > 0:
            scored.append((score, memory))

    scored.sort(key=lambda item: item[0], reverse=True)

    return [memory for _, memory in scored[:limit]]

def update_memory(memory_id, fact, category):
    """Edit an existing memory."""
    with get_connection() as conn:
        _execute(
            conn,
            """
            UPDATE memories
            SET fact = ?, category = ?
            WHERE id = ?
            """,
            (fact.strip(), category, memory_id),
        )

def clear_all_memories():
    """Delete every saved memory."""
    with get_connection() as conn:
        _execute(conn, "DELETE FROM memories")


def get_preference(key, default=None):
    """Return one persisted app preference."""
    with get_connection() as conn:
        row = _execute(
            conn,
            "SELECT value FROM app_preferences WHERE key = ?",
            (key,),
        ).fetchone()
        return row["value"] if row else default


def get_all_preferences():
    """Return persisted app preferences as a key/value mapping."""
    with get_connection() as conn:
        rows = _execute(
            conn,
            "SELECT key, value FROM app_preferences ORDER BY key",
        ).fetchall()
        return {row["key"]: row["value"] for row in rows}


def set_preference(key, value):
    """Create or update one persisted app preference."""
    with get_connection() as conn:
        _execute(
            conn,
            """
            INSERT INTO app_preferences (key, value)
            VALUES (?, ?)
            ON CONFLICT(key) DO UPDATE SET value = excluded.value
            """,
            (key, str(value)),
        )


def delete_conversation(conversation_id):
    """Delete a conversation and all its messages."""
    with get_connection() as conn:
        _execute(
            conn,
            "DELETE FROM messages WHERE conversation_id = ?",
            (conversation_id,),
        )
        _execute(
            conn,
            "DELETE FROM conversations WHERE id = ?",
            (conversation_id,),
        )